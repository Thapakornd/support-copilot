from datetime import datetime
from typing import Protocol

from support_copilot.domain.embedding_job import (
    EmbeddingJob,
    QueueObservation,
    RecoveryResult,
)
from support_copilot.domain.entities import (
    EvidencePassage,
    GenerationResult,
    RetrievedPassage,
)


class LLMPort(Protocol):
    def answer(
        self, question: str, passages: tuple[EvidencePassage, ...]
    ) -> GenerationResult: ...


class RetrieverPort(Protocol):
    def resolve_category(self, category: str) -> str | None: ...
    def retrieve(
        self, vector: list[float], category: str | None, limit: int
    ) -> list[RetrievedPassage]: ...


class EncoderPort(Protocol):
    def token_count(self, text: str, *, query: bool = False) -> int: ...
    def encode_documents(self, texts: list[str]) -> list[list[float]]: ...
    def encode_queries(self, texts: list[str]) -> list[list[float]]: ...


class ChunkerPort(Protocol):
    def chunks(self, snapshot: dict, config, encoder: EncoderPort) -> list[dict]: ...


class LeasePort(Protocol):
    def renew(self, job: EmbeddingJob) -> bool: ...


class EmbeddingStorePort(LeasePort, Protocol):
    def now(self) -> datetime: ...
    def recover(self, cutoff: datetime) -> RecoveryResult: ...
    def claim(self, config_hash: str, cutoff: datetime) -> EmbeddingJob | None: ...
    def fail(self, job: EmbeddingJob, code: str, retryable: bool) -> str: ...
    def observe(self, config_hash: str, cutoff: datetime) -> QueueObservation: ...
    def is_current(self, job: EmbeddingJob) -> bool: ...
    def load_snapshot(self, job: EmbeddingJob) -> dict: ...
    def publish(
        self, job: EmbeddingJob, chunks: list[dict], vectors: list[list[float]]
    ) -> str: ...
    def admit(self, config, document_ids: list[str] | None): ...
    def retry_failed(self, job_id): ...
    def validate_configuration(self, config): ...
